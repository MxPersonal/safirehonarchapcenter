import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=name=>readFileSync(new URL('../'+name,import.meta.url),'utf8');
const home=read('app/page.tsx');
const loop=read('components/creative-marquee.tsx');
const css=read('app/marquee-motion.css');
const layout=read('app/layout.tsx');
const store=read('lib/store.ts');
const productCards=read('components/showcase.tsx');
const gallery=read('components/design-card.tsx');
const sample=read('app/designs/[slug]/page.tsx');
const admin=read('components/admin-artwork-preview.tsx');

assert.ok(home.includes('<CreativeMarquee locale={locale}/>'),'Home must render the animated marquee.');
assert.ok(!home.includes('<section className="expressive-marquee-block"'),'Static strip must be removed.');
assert.ok(loop.includes('[0,1].map(copy=>'),'Exactly two identical content segments required.');
assert.ok(loop.includes('aria-hidden="true"')&&loop.includes('aria-label={accessible}'),'Motion must be accessible.');
assert.ok(css.includes('animation:safire-creative-marquee 24s linear infinite'),'Ticker must animate.');
assert.ok(css.includes('translate3d(-50%,0,0)'),'Loop must translate by exactly one duplicate.');
assert.ok(css.includes('@media(max-width:750px)'),'Animation must be mobile-friendly.');
assert.ok(css.includes('prefers-reduced-motion:reduce'),'Respect reduced-motion preference.');
assert.ok(layout.includes("import './marquee-motion.css'"),'Marquee stylesheet must be enabled.');
assert.ok(!store.includes("translatedFields(p,locale,'product')"),'Product data must not change with locale.');
assert.ok(store.includes("translatedFields(c,locale,'category')"),'Categories must remain localized.');
assert.ok(productCards.includes('locale="fa"'),'Printed product design artwork must remain unchanged.');
assert.ok(gallery.includes('locale="fa"'),'Sample product imagery must remain unchanged.');
assert.ok(sample.includes('const title=d.name;'),'Sample product titles must remain unchanged.');
assert.ok(admin.includes('locale="fa"'),'Admin product artwork must remain unchanged.');
console.log('15 marquee + product-invariance regression checks passed.');
